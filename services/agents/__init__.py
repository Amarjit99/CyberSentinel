class AgentExecutionRequest(BaseModel):
    """Execution request dispatching an agent on an incident task."""

    run_id: str = Field(..., description="Unique agent run identifier")
    agent_id: AgentIdEnum = Field(..., description="Target autonomous agent")
    incident_id: str = Field(..., description="Associated incident ID")
    task_type: str = Field(..., description="Specific analysis task type")
    model_ref: str = Field(..., description="Designated LLM or SLM reference")
    budget_limit_usd: float = Field(default=1.0, description="Cost limit threshold")


class AgentFindingResult(BaseModel):
    """Structured output generated by an agent upon task completion."""

    finding_type: str = Field(..., description="Finding classification")
    claim: str = Field(..., description="Human-readable deduction or hypothesis")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Agent confidence score")
    evidence_refs: List[str] = Field(
        default_factory=list, description="IDs of backing evidence records"
    )
    limitations: Optional[str] = Field(
        default=None, description="Known analytical caveats or blindspots"
    )


class BaseAgentExecutor(ABC):
    """Abstract interface for agent task dispatch."""

    @abstractmethod
    async def execute_task(self, request: AgentExecutionRequest) -> List[AgentFindingResult]:
        """Execute agent workflow without invoking shell or live response tools."""
        raise NotImplementedError


